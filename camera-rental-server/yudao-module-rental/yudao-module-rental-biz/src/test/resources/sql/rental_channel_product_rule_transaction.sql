DROP TABLE IF EXISTS rental_channel_product_sku_mapping;
DROP TABLE IF EXISTS rental_channel_product_rule;
DROP TABLE IF EXISTS rental_device_model;
DROP TABLE IF EXISTS xianyu_product_sku;
DROP TABLE IF EXISTS xianyu_product;
DROP TABLE IF EXISTS xianyu_shop;
DROP TABLE IF EXISTS xianyu_application;

CREATE TABLE xianyu_application (
    id bigint NOT NULL,
    tenant_id bigint NOT NULL,
    application_code varchar(64),
    display_name varchar(128),
    enabled boolean,
    base_url varchar(255),
    app_key varchar(128),
    app_secret varchar(255),
    webhook_base_url varchar(255),
    write_enabled boolean,
    job_enabled boolean,
    lookback_days int,
    overlap_minutes int,
    max_pages_per_shop int,
    page_size int,
    push_retry_stale_seconds int,
    push_retry_batch_size int,
    authorization_status varchar(32),
    authorization_expires_at timestamp,
    creator varchar(64) DEFAULT '',
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater varchar(64) DEFAULT '',
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted boolean NOT NULL DEFAULT false,
    PRIMARY KEY (id)
);

CREATE TABLE xianyu_shop (
    id bigint NOT NULL,
    tenant_id bigint NOT NULL,
    application_id bigint,
    external_shop_id varchar(128),
    xianyu_user_name varchar(128),
    authorize_id varchar(128),
    shop_name varchar(255),
    authorization_status varchar(32),
    authorization_expires_at timestamp,
    guarantee_status varchar(32),
    source_updated_at timestamp,
    creator varchar(64) DEFAULT '',
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updater varchar(64) DEFAULT '',
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted boolean NOT NULL DEFAULT false,
    PRIMARY KEY (id)
);

CREATE TABLE xianyu_product (
    id bigint NOT NULL,
    tenant_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    xgj_product_id varchar(128),
    xianyu_item_id varchar(128),
